export const PRESET_IDS = Object.freeze(BUILT_IN_PRESETS.map((preset) => preset.id));

export function builtInPresetById(id) {
  return BUILT_IN_PRESETS.find((preset) => preset.id === id) || null;
}

export function findPreset(id, customPresets = []) {
  const custom = Array.isArray(customPresets) ? customPresets.find((preset) => preset?.id === id) : null;
  return custom || builtInPresetById(id) || null;
}
